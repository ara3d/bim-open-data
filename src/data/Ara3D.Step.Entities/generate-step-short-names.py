"""Regenerates StepShortNames.tsv, the ISO 10303 entity short names (CRTPNT -> CARTESIAN_POINT).

Source: Open CASCADE Technology (OCCT), RWStepAP214_ReadWriteModule.cxx, which binds each AP203/AP214 entity's long
name (theTypenums) and short name (theTypeshor) to one type number. OCCT is LGPL 2.1 with an exception; only the
facts (the pairs of names, which ISO 10303 publishes per application protocol) are copied, not code.
  https://github.com/Open-Cascade-SAS/OCCT/blob/master/src/DataExchange/TKDESTEP/RWStepAP214/RWStepAP214_ReadWriteModule.cxx
Run: python -I generate-step-short-names.py <path to that .cxx> [StepShortNames.tsv]
A short name OCCT binds to two long names (CMRPIT) is dropped.
Pairs whose long name AP242's EXPRESS (Ara3D.StepTypes) does not declare are kept; the index ignores them.
"""
import re, sys

text = open(sys.argv[1], encoding='utf8', errors='ignore').read()
names = dict(re.findall(r'static constexpr std::string_view (\w+)\(\s*"([^"]+)"\s*\)', text))

def bound(table):
    out = {}
    for m in re.finditer(r'^\s*' + table + r'\.Bind\((\w+),\s*(\d+)\)', text, re.M):
        out.setdefault(int(m.group(2)), []).append(names[m.group(1)])
    return out

longs, shorts = bound('theTypenums'), bound('theTypeshor')
rows = sorted({(s, l) for n, ss in shorts.items() for s in ss for l in longs.get(n, [])})
by_short = {}
for s, l in rows:
    by_short.setdefault(s, []).append(l)
for s, ls in by_short.items():
    if len(ls) > 1:
        print('dropped, ambiguous in OCCT:', s, ls)
rows = [(s, l) for s, l in rows if len(by_short[s]) == 1]
with open(sys.argv[2] if len(sys.argv) > 2 else 'StepShortNames.tsv', 'w', newline='\n') as f:
    f.write('# short name <TAB> long name. Generated by generate-step-short-names.py from OCCT; do not edit.\n')
    for s, l in rows:
        f.write(f'{s}\t{l}\n')
print(len(rows), 'pairs')
