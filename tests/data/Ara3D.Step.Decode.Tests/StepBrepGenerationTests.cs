using System.Diagnostics;

namespace Ara3D.Step.Decode.Tests;

/// <summary>The committed src/data/Ara3D.StepBrep is what tools/regen-step-brep.ps1 writes from the Plato and
/// library checkouts beside this repository (bim-open-toolkit/deps/bim-open-data, ..\..\..\plato and
/// ..\..\sandbox\step-brep-mesh). Ignored when either is absent; otherwise it regenerates from the pinned Plato commit
/// and the library's HEAD (never from either working tree), which takes minutes.</summary>
public static class StepBrepGenerationTests
{
    const string Script = "tools/regen-step-brep.ps1";
    const string HeaderStart = "// Generated by tools/regen-step-brep.ps1 from ";

    [Test]
    public static void CommittedOutputIsCurrent()
    {
        var repo = RepositoryRoot();
        var plato = Path.GetFullPath(Path.Combine(repo, "..", "..", "..", "plato"));
        var library = Path.GetFullPath(Path.Combine(repo, "..", "..", "sandbox", "step-brep-mesh"));
        if (!Directory.Exists(plato) || !Directory.Exists(library))
            Assert.Ignore($"needs the Plato checkout ({plato}) and the library ({library}); run {Script} with -PlatoRoot and -LibraryRoot to regenerate");
        var output = Path.Combine(Path.GetTempPath(), "step-brep-" + Guid.NewGuid().ToString("N"));
        try
        {
            RunScript(repo, $"-OutputRoot \"{output}\"");
            var committed = Path.Combine(repo, "src", "data", "Ara3D.StepBrep");
            foreach (var folder in new[] { "Generated", "Intrinsics" })
                Assert.That(Listing(Path.Combine(committed, folder)), Is.EqualTo(Listing(Path.Combine(output, folder))),
                    $"{folder} differs from a fresh {Script}; rerun it and commit the result");
        }
        finally
        {
            if (Directory.Exists(output))
                Directory.Delete(output, true);
        }
    }

    /// <summary>Each file's name and its text without the header line, line endings normalized.</summary>
    static IReadOnlyList<string> Listing(string folder)
        => Directory.GetFiles(folder, "*.cs").Order(StringComparer.Ordinal)
            .Select(f => Path.GetFileName(f) + "\n" + string.Join("\n", File.ReadLines(f).Where(l => !l.StartsWith(HeaderStart, StringComparison.Ordinal))))
            .ToList();

    /// <summary>Runs the script with the arguments and returns what it printed.</summary>
    static string RunScript(string repo, string arguments)
    {
        var shell = OperatingSystem.IsWindows() ? "powershell" : "pwsh";
        var start = new ProcessStartInfo(shell, $"-NoProfile -ExecutionPolicy Bypass -File \"{Path.Combine(repo, Script)}\" {arguments}")
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
        };
        using var process = Process.Start(start)!;
        var log = process.StandardOutput.ReadToEndAsync();
        var errors = process.StandardError.ReadToEndAsync();
        process.WaitForExit();
        Assert.That(process.ExitCode, Is.Zero, () => $"{Script} failed:\n{log.Result}\n{errors.Result}");
        return log.Result;
    }

    static string RepositoryRoot()
    {
        var dir = new DirectoryInfo(TestContext.CurrentContext.TestDirectory);
        while (dir != null && !File.Exists(Path.Combine(dir.FullName, "BimOpenData.sln")))
            dir = dir.Parent;
        return dir?.FullName ?? throw new DirectoryNotFoundException("BimOpenData.sln not found above the test directory");
    }
}
