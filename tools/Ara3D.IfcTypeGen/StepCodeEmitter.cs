using System.Text;

namespace Ara3D.IfcTypeGen;

/// <summary>
/// Writes the Ara3D.StepTypes source for one STEP long form. Per entity: an interface that extends its
/// supertypes' interfaces and the SELECTs that list it, so membership works with several supertypes; and a
/// sealed descriptor class with one StepAttribute field per slot of its simple-instance record, inherited slots
/// included. Per SELECT an interface, per ENUMERATION an enum. Declarations are in ordinal name order, so an
/// unchanged schema gives byte-identical files.
/// </summary>
public sealed class StepCodeEmitter
{
    public const string Namespace = "Ara3D.StepTypes";

    public static readonly IReadOnlySet<string> ReservedTypes = new HashSet<string>
    {
        "StepEntityType", "StepAttribute", "IStepValue", "IStepEntity", "IStepSelect", "StepSchema", "IReadOnlyList",
    };

    private readonly string _source;
    private readonly IReadOnlyDictionary<string, ExpressEntity> _lookup;
    private readonly StepTypeMap _types;
    private readonly IReadOnlyList<ExpressEntity> _entities;
    private readonly IReadOnlyList<ExpressSelect> _selects;
    private readonly IReadOnlyList<ExpressEnumeration> _enums;
    private readonly ILookup<string, string> _selectsListing;

    public StepCodeEmitter(ExpressSchema schema, string source)
    {
        _source = source;
        _lookup = schema.ToEntityLookup();
        _types = new StepTypeMap(schema);
        _entities = schema.Entities.OrderBy(e => e.Name, StringComparer.Ordinal).ToList();
        _selects = schema.Decls.OfType<ExpressSelect>().OrderBy(s => s.Name, StringComparer.Ordinal).ToList();
        _enums = schema.Decls.OfType<ExpressEnumeration>().OrderBy(e => e.Name, StringComparer.Ordinal).ToList();
        _selectsListing = _selects
            .SelectMany(s => s.Options.Select(o => (Option: o, Select: s.Name)))
            .ToLookup(p => p.Option, p => p.Select, StringComparer.OrdinalIgnoreCase);
        CheckTypeNames();
    }

    /// <summary>File name to contents, for every generated file.</summary>
    public IReadOnlyDictionary<string, string> Files()
        => new Dictionary<string, string>
        {
            ["Entities.g.cs"] = Entities(),
            ["Interfaces.g.cs"] = Interfaces(),
            ["Enums.g.cs"] = Enums(),
            ["Schema.g.cs"] = Schema(),
        };

    private void CheckTypeNames()
    {
        var names = _entities.SelectMany(e => new[] { e.Name.ToPascal(), e.Name.ToInterface() })
            .Concat(_selects.Select(s => s.Name.ToInterface()))
            .Concat(_enums.Select(e => e.Name.ToPascal()))
            .Concat(ReservedTypes)
            .ToList();
        var clashes = names.GroupBy(n => n).Where(g => g.Count() > 1).Select(g => g.Key).ToList();
        if (clashes.Count > 0)
            throw new InvalidOperationException($"Generated type names collide: {string.Join(", ", clashes)}");
    }

    private StringBuilder Header(bool usesLists = false)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"// Generated by tools/Ara3D.IfcTypeGen (StepCodeGenTest.TestGenerate) from {_source}. Do not edit.");
        if (usesLists)
            sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine($"namespace {Namespace};");
        return sb;
    }

    public string Interfaces()
    {
        var sb = Header();
        foreach (var e in _entities)
        {
            var bases = e.Supertypes.Select(StepNames.ToInterface).DefaultIfEmpty("IStepEntity").Concat(SelectInterfaces(e.Name));
            sb.AppendLine();
            sb.AppendLine($"public interface {e.Name.ToInterface()} : {string.Join(", ", bases)} {{ }}");
        }
        foreach (var s in _selects)
        {
            var bases = SelectInterfaces(s.Name).DefaultIfEmpty("IStepSelect");
            sb.AppendLine();
            sb.AppendLine($"public interface {s.Name.ToInterface()} : {string.Join(", ", bases)} {{ }}");
        }
        return sb.ToString();
    }

    private IEnumerable<string> SelectInterfaces(string name)
        => _selectsListing[name].OrderBy(s => s, StringComparer.Ordinal).Select(StepNames.ToInterface);

    public string Entities()
    {
        var sb = Header(usesLists: true);
        foreach (var e in _entities)
            AppendEntity(sb, e);
        return sb.ToString();
    }

    private void AppendEntity(StringBuilder sb, ExpressEntity e)
    {
        var className = e.Name.ToPascal();
        var slots = _lookup.Layout(e.Name);
        var fields = slots.FieldNames(className);
        sb.AppendLine();
        sb.AppendLine($"public sealed class {className} : StepEntityType, {e.Name.ToInterface()}");
        sb.AppendLine("{");
        sb.AppendLine($"    public static readonly {className} Instance = new();");
        sb.AppendLine();
        sb.AppendLine($"    private {className}()");
        sb.AppendLine($"        : base(\"{e.Name.ToUpperInvariant()}\")");
        sb.AppendLine($"        => Attributes = [{string.Join(", ", fields)}];");
        sb.AppendLine();
        sb.AppendLine("    public override IReadOnlyList<StepAttribute> Attributes { get; }");
        for (var i = 0; i < slots.Count; i++)
        {
            var s = slots[i];
            var derived = s.IsDerived ? ", true" : "";
            sb.AppendLine($"    public readonly StepAttribute<{_types.ToCSharp(s.Attribute.TypeExpr)}> {fields[i]} = new(\"{s.Attribute.Name}\", \"{s.Entity.ToUpperInvariant()}\", {s.Position}, {s.OwnPosition}{derived});");
        }
        sb.AppendLine("}");
    }

    public string Enums()
    {
        var sb = Header();
        foreach (var e in _enums)
        {
            var name = e.Name.ToPascal();
            if (e.Options.Select(StepNames.ToMatchKey).Distinct().Count() != e.Options.Count)
                throw new InvalidOperationException($"{e.Name}: two items differ only in underscores or case");
            if (e.Options.Any(o => o.ToPascal() == name))
                throw new InvalidOperationException($"{e.Name}: an item has the enumeration's own name");
            sb.AppendLine();
            sb.AppendLine($"public enum {name}");
            sb.AppendLine("{");
            foreach (var o in e.Options)
                sb.AppendLine($"    {o.ToPascal()},");
            sb.AppendLine("}");
        }
        return sb.ToString();
    }

    public string Schema()
    {
        var sb = Header(usesLists: true);
        sb.AppendLine();
        sb.AppendLine("public static class StepSchema");
        sb.AppendLine("{");
        sb.AppendLine($"    public const int EntityCount = {_entities.Count};");
        sb.AppendLine();
        sb.AppendLine("    public static readonly IReadOnlyList<StepEntityType> Entities =");
        sb.AppendLine("    [");
        foreach (var e in _entities)
            sb.AppendLine($"        {e.Name.ToPascal()}.Instance,");
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        return sb.ToString();
    }
}
